/**
 * Writes src/engine/data-item-facts.ts from OpenDota's item constants: each shop item's dispel, who it
 * reaches, and whether it is an attack item.
 *
 *   npm run item-facts
 *
 * Rerun it after a patch and review the diff: every changed line changes which answer items the engine
 * offers.
 */
import { writeFileSync } from "node:fs";
import { fetchItemFacts } from "../src/data/item-facts";

const OUT = new URL("../src/engine/data-item-facts.ts", import.meta.url);

const facts = await fetchItemFacts();
const keys = Object.keys(facts).sort((a, b) => a.localeCompare(b));
writeFileSync(
  OUT,
  [
    `// Generated by \`npm run item-facts\` from OpenDota's item constants on ${new Date().toISOString().slice(0, 10)}.`,
    "// Do not edit by hand: rerun the script after a patch and review the diff.",
    'import type { ItemFact } from "./item-facts";',
    "",
    "export const ITEM_FACTS: Readonly<Record<string, ItemFact>> = {",
    ...keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(facts[k])},`),
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote item facts for ${keys.length} items.`);
