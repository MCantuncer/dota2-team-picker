/**
 * Writes src/engine/data-lane-facts.ts from OpenDota's game constants: hero base stats and the lane numbers
 * of each spell, which the lane tactics are worked out from.
 *
 *   npm run lane-facts
 *
 * Rerun it after a patch and review the diff: every changed number changes a lane tactic.
 */
import { writeFileSync } from "node:fs";
import { fetchLaneFacts } from "../src/data/lane-facts";

const OUT = new URL("../src/engine/data-lane-facts.ts", import.meta.url);

const facts = await fetchLaneFacts();
const heroIds = Object.keys(facts.heroes).sort((a, b) => Number(a) - Number(b));
const spellKeys = Object.keys(facts.spells).sort();
writeFileSync(
  OUT,
  [
    `// Generated by \`npm run lane-facts\` from OpenDota's game constants on ${new Date().toISOString().slice(0, 10)}.`,
    "// Do not edit by hand: rerun the script after a patch and review the diff.",
    'import type { LaneFacts } from "./lane-facts";',
    "",
    "export const LANE_FACTS: LaneFacts = {",
    "  heroes: {",
    ...heroIds.map((id) => `    ${JSON.stringify(id)}: ${JSON.stringify(facts.heroes[id])},`),
    "  },",
    "  spells: {",
    ...spellKeys.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(facts.spells[k])},`),
    "  },",
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote lane facts for ${heroIds.length} heroes and ${spellKeys.length} spells.`);
