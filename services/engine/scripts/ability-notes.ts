/**
 * Writes src/engine/data-ability-notes.ts from Valve's ability notes: Break, Linken's Sphere, dodging,
 * invisible heroes, debuff immunity, illusions and kills through saves.
 *
 *   npm run ability-notes
 *
 * Rerun it after a patch and review the diff: each changed line changes advice the engine gives.
 */
import { writeFileSync } from "node:fs";
import { fetchAbilityNotes } from "../src/data/ability-notes";

const OUT = new URL("../src/engine/data-ability-notes.ts", import.meta.url);

const notes = await fetchAbilityNotes();
const keys = Object.keys(notes);
writeFileSync(
  OUT,
  [
    `// Generated by \`npm run ability-notes\` from Valve's ability notes on ${new Date().toISOString().slice(0, 10)}.`,
    "// Do not edit by hand: rerun the script after a patch and review the diff.",
    'import type { AbilityNotes } from "./ability-notes";',
    "",
    "export const ABILITY_NOTES: AbilityNotes = {",
    ...keys.map((key) => `  ${key}: ${JSON.stringify(notes[key])},`),
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote rules for ${keys.length} abilities and items.`);
